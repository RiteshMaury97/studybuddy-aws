import {
  Accessibility,
  BarChart3,
  BookMarked,
  BookOpen,
  CalendarCheck,
  CalendarDays,
  CheckCircle2,
  ClipboardList,
  Download,
  FileText,
  Layers3,
  Lightbulb,
  ListTodo,
  Mic,
  Network,
  Plus,
  RotateCcw,
  Search,
  StickyNote,
  Target,
  Timer,
  Trash2,
  WandSparkles,
} from "lucide-react";

export default function FlashcardsPage({ app }) {
  const {
    page,
    flashTopic,
    setFlashTopic,
    flashcards,
    setFlashcards,
    revealed,
    setRevealed,
    generateCards,
  } = app;
  return (
    <section className="workspace-page">
      <div className="feature-intro">
        <div className="feature-icon">
          <Layers3 />
        </div>
        <div>
          <h2>Practice active recall.</h2>
          <p>
            Create starter flashcards for a topic, flip them to check your
            thinking, and save them for review. AI-generated cards can be added
            once the backend supports structured card output.
          </p>
        </div>
      </div>
      <div className="panel flash-create">
        <label>
          What topic are you studying?
          <input
            value={flashTopic}
            onChange={(e) => setFlashTopic(e.target.value)}
            placeholder="e.g. HTTP status codes, photosynthesis, recursion"
            onKeyDown={(e) => {
              if (e.key === "Enter") generateCards();
            }}
          />
        </label>
        <button className="send-btn" onClick={generateCards}>
          <Plus size={16} /> Create practice cards
        </button>
        <small>
          Creates editable practice prompts locally; it does not claim these
          cards were generated by AI.
        </small>
      </div>
      <div className="list-heading">
        <h3>
          Your cards <span className="count-pill">{flashcards.length}</span>
        </h3>
        <button
          className="text-action"
          onClick={() => {
            setFlashcards([]);
            setRevealed({});
          }}
        >
          Clear all
        </button>
      </div>
      <div className="flash-grid">
        {flashcards.map((c) => (
          <button
            key={c.id}
            className={`flash-card ${revealed[c.id] ? "revealed" : ""}`}
            onClick={() =>
              setRevealed((prev) => ({ ...prev, [c.id]: !prev[c.id] }))
            }
          >
            <span>{revealed[c.id] ? "ANSWER" : c.topic.toUpperCase()}</span>
            <strong>{revealed[c.id] ? c.answer : c.question}</strong>
            <small>
              {revealed[c.id] ? "Tap to see question" : "Tap to reveal answer"}
            </small>
          </button>
        ))}
      </div>
      {flashcards.length === 0 && (
        <div className="empty-state">
          <Layers3 size={25} />
          <strong>No cards yet</strong>
          <span>Enter a topic above to create your first practice set.</span>
        </div>
      )}
    </section>
  );
}
